function cleanQueryText(raw: string): string {
  return raw
    .trim()
    .toLowerCase()
    .split(/(\s+)/)
    .map((part) => {
      const clean = part.replace(/[^a-z0-9]/g, "");
      if (TYPO_MAP[clean]) {
        return TYPO_MAP[clean];
      }
      return part;
    })
    .join("");
}

