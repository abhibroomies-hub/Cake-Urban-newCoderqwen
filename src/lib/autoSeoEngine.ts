function slugifyTheme(raw: string): string {
  const clean = cleanQueryText(raw)
    .replace(/[^a-z0-9\s-]/g, "")
    .trim()
    .replace(/\s+/g, "-");
  if (!clean) return "";
  return clean.endsWith("-cake") ? clean : `${clean}-cake`;
}

function formatThemeLabel(raw: string): string {
  const clean = cleanQueryText(raw)
    .replace(/\b(custom|cake|cakes|design|designs)\b/gi, "")
    .replace(/\s+/g, " ")
    .trim();
  if (!clean) return "Custom Theme Cake";
  const titled = clean.replace(/\b\w/g, (c) => c.toUpperCase());
  return `${titled} Cake`;
}

export function getAutoSeoThemes(): AutoIndexedCakeTheme[] {
  const baseMap = new Map<string, AutoIndexedCakeTheme>();

  for (const extra of SEED_EXTRA_THEMES) {
    baseMap.set(extra.slug, extra);
  }

  if (typeof window !== "undefined") {
    try {
      const raw = localStorage.getItem(AUTO_SEO_LS_KEY);
      if (raw) {
        const saved: AutoIndexedCakeTheme[] = JSON.parse(raw);
        if (Array.isArray(saved)) {
          for (const item of saved) {
            if (item && item.slug && item.label) {
              const existing = baseMap.get(item.slug);
              baseMap.set(item.slug, {
                ...existing,
                ...item,
                searchCount: Math.max(existing?.searchCount || 1, item.searchCount || 1),
              });
            }
          }
        }
      }
    } catch {
      // Ignore storage read errors
    }
  }

  return Array.from(baseMap.values()).sort((a, b) => b.searchCount - a.searchCount);
}

let rtdbSyncInitialized = false;
const listeners = new Set<() => void>();

export function subscribeAutoSeoUpdates(cb: () => void): () => void {
  listeners.add(cb);
  initAutoSeoRealtimeSync();
  return () => {
    listeners.delete(cb);
  };
}

function notifyListeners() {
  listeners.forEach((cb) => {
    try {
      cb();
    } catch {}
  });
}

export function initAutoSeoRealtimeSync() {
  if (rtdbSyncInitialized || typeof window === "undefined") return;
  rtdbSyncInitialized = true;

  try {
    const rootRef = (ref as any)(rtdb);
    const seoNode = (child as any)(rootRef, "autoSeoKeywords");
    onValue(seoNode, (snapshot: any) => {
      if (snapshot.exists()) {
        const val = snapshot.val();
        if (val && typeof val === "object") {
          const remoteItems = Object.values(val) as AutoIndexedCakeTheme[];
          const current = getAutoSeoThemes();
          const mergedMap = new Map<string, AutoIndexedCakeTheme>();
          for (const item of current) mergedMap.set(item.slug, item);
          for (const rItem of remoteItems) {
            if (rItem && rItem.slug && rItem.label) {
              const prev = mergedMap.get(rItem.slug);
              mergedMap.set(rItem.slug, {
                ...prev,
                ...rItem,
                searchCount: Math.max(prev?.searchCount || 1, rItem.searchCount || 1),
              });
            }
          }
          const customOnly = Array.from(mergedMap.values());
          try {
            localStorage.setItem(AUTO_SEO_LS_KEY, JSON.stringify(customOnly.slice(0, 150)));
          } catch {}
          notifyListeners();
        }
      }
    });
  } catch {
    // Offline or RTDB unavailable
  }
}

export function recordAutoSeoSearch(rawQuery: string) {
  if (typeof window === "undefined") return;
  const normalized = cleanQueryText(rawQuery);
  if (!normalized || normalized.length < 3 || normalized.length > 48) return;

  // Ignore single-letter or partial typing fragments under 3 chars
  const words = normalized.split(/\s+/).filter(Boolean);
  if (words.some((w) => w.length === 1 && !/\d/.test(w))) return;

  const slug = slugifyTheme(normalized);
  if (!slug || slug.length < 6) return;

  const label = formatThemeLabel(normalized);
  const queryClean = label;
  const desc = `Custom 100% pure eggless ${label} freshly baked to order with 30-45 mins express & 12 AM midnight delivery across Faridabad, Gurgaon, Noida, Delhi & Ghaziabad`;

  try {
    const current = getAutoSeoThemes();
    const existing = current.find((x) => x.slug === slug);
    const updatedItem: AutoIndexedCakeTheme = existing
      ? {
          ...existing,
          searchCount: (existing.searchCount || 1) + 1,
          lastSearchedAt: new Date().toISOString(),
        }
      : {
          slug,
          label,
          query: queryClean,
          desc,
          searchCount: 5,
          lastSearchedAt: new Date().toISOString(),
          autoGenerated: true,
        };

    // Save locally
    const rawSaved = localStorage.getItem(AUTO_SEO_LS_KEY);
    const savedList: AutoIndexedCakeTheme[] = rawSaved ? JSON.parse(rawSaved) : [];
    const filtered = savedList.filter((x) => x.slug !== slug);
    filtered.unshift(updatedItem);
    localStorage.setItem(AUTO_SEO_LS_KEY, JSON.stringify(filtered.slice(0, 150)));

    // Sync to Firebase RTDB so all users & crawlers get the new SEO keyword automatically
    try {
      const rootRef = (ref as any)(rtdb);
      Promise.resolve(
        (rtdbSet as any)((child as any)(rootRef, `autoSeoKeywords/${slug}`), updatedItem)
      ).catch(() => {});
    } catch {}

    // Notify backend sitemap/GEO feed in background
    fetch("/api/seo-auto-index", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ slug, label, query: queryClean, desc }),
    }).catch(() => {});

    notifyListeners();
  } catch {
    // Ignore storage quota errors
  }
}
